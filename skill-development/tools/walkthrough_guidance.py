#!/usr/bin/env python3
"""Author-selected actions for synthetic dialogue cases; this does NOT replay an LLM.

The script checks the selected local actions and evidence. Reply text is authored
for design review, not generated by an independent agent or scored by regex.
"""

import argparse
import hashlib
import json
from pathlib import Path
import sys

DEV = Path(__file__).resolve().parents[1]
SCRIPTS = DEV / "skills/qa-workflow/scripts"
sys.path.insert(0, str(SCRIPTS))
from qa import execute
from qaw import VERSION
from qaw.storage import Error


def snapshot(root):
    return {p.relative_to(root).as_posix(): hashlib.sha256(p.read_bytes()).hexdigest()
            for p in root.rglob("*") if p.is_file()} if root.exists() else {}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--output", required=True)
    args = parser.parse_args()
    out = Path(args.output).resolve()
    out.mkdir(parents=True, exist_ok=False)
    reports, traces = [], []

    def call(root, action, **fields):
        request = {"action": action, "actor": "lead", **fields}
        try:
            result = execute(root, request)
            traces.append({"action": action, "ok": True, "result": result})
            return result
        except Error as exc:
            traces.append({"action": action, "ok": False, "code": exc.code})
            raise

    def reject(code, root, action, **fields):
        try:
            call(root, action, **fields)
        except Error as exc:
            assert exc.code == code, (exc.code, code)
            return
        raise AssertionError("Expected rejection: " + code)

    def record(key, user, reply, evidence, kind="selected_local_actions_checked"):
        reports.append({"id": key, "user": user, "authored_reply": reply,
                        "evidence": evidence, "method": kind, "model_replay_executed": False})

    def fixture(key, with_task=False, unknown=False):
        folder = out / key
        folder.mkdir()
        root = folder / "workspace"
        call(root, "workspace.init", title="虚构引导走读", actor="lead")
        for project, title in [("orders", "订单咨询历史"), ("catalog", "目录菜单管理")]:
            call(root, "project.create", project=project, title=project, systems={"client": "客户端", "admin": "管理端"})
            call(root, "requirement.create", project=project, requirement="12345", title=title)
        ctx = {"project": "orders", "requirement": "12345"}
        source = folder / "synthetic-cases.txt"
        source.write_text("虚构用例与证据夹具；没有执行真实业务或读取真实页面。\n")
        proof = call(root, "artifact.import", **ctx, artifact="proof", source_path=str(source), purpose="虚构走读夹具")
        if with_task or unknown:
            call(root, "task.create", **ctx, task="worker", owner="alice", scope="虚构执行", run="round-1",
                 cases=["view", "approve"], inputs=["proof"], context={"environment": "fixture", "build": "v1", "roles": ["demo-role"]})
            call(root, "case.record", **ctx, task="worker", actor="alice", case="view", status="passed", basis="仅模拟状态",
                 evidence=["proof"], expected_revision=0)
        if unknown:
            held = call(root, "resource.acquire", **ctx, task="worker", actor="alice", resource="demo:submit")
            call(root, "operation.prepare", **ctx, task="worker", actor="alice", operation="write-1", resource="demo:submit",
                 resource_revision=held["revision"], intent="虚构提交记录", correlation="fixture-1", target="fixture-service")
            call(root, "operation.dispatch", **ctx, task="worker", actor="alice", operation="write-1", expected_revision=1)
        return root, ctx, source, proof

    # Pure help: no project is needed and no project is initialized.
    empty = out / "help-without-project"
    assert not empty.exists()
    capability = call(empty, "capabilities")
    assert not empty.exists()
    record("help-purpose", "这个 Skill 是什么？", "它帮你组织测试项目、资料和进度，也方便换会话后接着做。",
           {"version": capability["version"], "workspace_created": False})
    record("help-capabilities", "能帮我干什么？", "当前可用的是项目与状态管理、协作记录和本地备份；实际页面和平台操作还要看已有工具与任务范围。",
           {"implemented_groups": len(capability["implemented_local"]), "unimplemented_groups": len(capability["not_implemented_as_builtin"])})
    record("help-workflow", "流程是什么样的？", "通常从需求澄清到用例、执行、BUG 与修复验证。你也可以从已有资料接着做。",
           {"workflow": capability["target_test_workflow"], "development_roadmap_used_as_workflow": False})

    # Project preparation does not require a requirement or environment.
    root = out / "new-project-only"
    call(root, "workspace.init", title="虚构新项目", actor="lead")
    call(root, "project.create", project="purchase", title="采购平台")
    listing = call(root, "list")
    assert listing["total"] == 1 and listing["items"][0]["kind"] == "project"
    record("new-project-only", "先把采购项目准备好，还没有需求。", "项目已记下。以后有需求材料时直接接着用，环境和账号到需要时再补。",
           {"project_count": 1, "requirement_count": 0})

    # Existing plain files are read without creating another state authority.
    legacy = out / "legacy"
    legacy.mkdir()
    (legacy / "README.md").write_text("虚构旧项目入口：正式用例在 cases.md，本次只评审用例。\n")
    (legacy / "cases.md").write_text("虚构旧用例；未提供执行结果。\n")
    before = snapshot(legacy)
    read_material = (legacy / "README.md").read_text() + (legacy / "cases.md").read_text()
    assert "只评审" in read_material and snapshot(legacy) == before
    assert not (legacy / "workspace.json").exists()
    record("legacy-readonly", "这些是老项目的用例，帮我看看。", "我会沿用现有用例和约定，先检查覆盖和步骤。现有资料没有执行结果，我不会把它当成已测完。",
           {"existing_files_preserved": True, "new_workspace_created": False})

    root, ctx, _, _ = fixture("ambiguous")
    before = snapshot(root)
    hits = call(root, "list", requirement="12345")
    assert {x["project"] for x in hits["items"]} == {"orders", "catalog"}
    assert snapshot(root) == before
    record("same-id-clarification", "继续 12345。", "你说的是订单的咨询历史，还是目录平台的菜单管理？",
           {"matching_projects": [x["project"] for x in hits["items"]], "state_unchanged": True})

    root, ctx, _, _ = fixture("resume", with_task=True)
    original = call(root, "run.summary", **ctx, run="round-1")
    call(root, "task.pause", **ctx, task="worker", note="虚构用户暂停", expected_revision=1)
    before = snapshot(root)
    call(root, "capabilities")
    paused = call(root, "resume", **ctx)
    assert paused["tasks"][0]["status"] == "paused" and snapshot(root) == before
    record("question-while-paused", "先问一下，你还能做哪些事？", "我可以解释当前能力。之前暂停的任务会保留在原位置，等你明确继续时再接上。",
           {"task_still_paused": True, "state_unchanged": True})
    call(root, "task.resume", **ctx, task="worker", actor="alice", note="虚构用户明确继续", expected_revision=2)
    assert call(root, "run.summary", **ctx, run="round-1") == original
    record("continue-known-task", "昨天那个接着弄吧。", "我查到了上次的进度，已完成的结果会保留，接着处理剩下的场景。",
           {"task_active": True, "recorded_results_preserved": original["recorded_results"]})

    root, ctx, _, _ = fixture("switch-with-unknown", unknown=True)
    other_path = root / "projects/catalog/requirements/12345/state.json"
    other = other_path.read_bytes()
    call(root, "task.pause", **ctx, task="worker", note="用户要求先放下并切换", expected_revision=1)
    old = call(root, "resume", **ctx)
    call(root, "resume", project="catalog", requirement="12345")
    assert old["tasks"][0]["status"] == "paused" and old["unconfirmed_operation_count"] == 1 and old["held_resource_count"] == 1
    assert other_path.read_bytes() == other
    record("switch-preserves-pending", "这个先放放，先看另一个项目。", "这边的进度已保存，还有一笔提交待核实。我会保留这个事项，现在先看另一个项目的资料。",
           {"source_paused": True, "pending_operations": 1, "held_resources": 1, "other_project_unchanged": True})
    before = snapshot(root)
    reject("HANDOFF_REQUIRED", root, "task.transfer", **ctx, task="worker", new_owner="bob", previous_owner_stopped=False,
           note="尚未核对旧执行者", expected_revision=2)
    assert snapshot(root) == before
    record("stuck-chat-handoff", "前面的会话卡了，你接着做。", "我找到了保存的记录。接手前还需要核对旧任务是否停下，以及那笔待核实提交的结果。",
           {"handoff_rejected": "HANDOFF_REQUIRED", "state_unchanged": True})

    root, ctx, _, proof = fixture("archived-lookup")
    call(root, "requirement.create", project="orders", requirement="old-sso", title="单点登录 v1")
    old_ctx = {"project": "orders", "requirement": "old-sso"}
    source = out / "archived-lookup/sso-cases-v1.md"
    source.write_text("虚构归档用例 v1；不是实际业务用例。\n")
    artifact = call(root, "artifact.import", **old_ctx, artifact="cases-v1", source_path=str(source), purpose="虚构历史用例")
    call(root, "requirement.archive", **old_ctx, archived=True, reason="虚构归档", expected_revision=1)
    before = snapshot(root)
    hits = call(root, "list", project="orders", query="单点登录", include_archived=True)
    saved = call(root, "record.read", path=artifact["path"])
    assert len(hits["items"]) == 1 and hits["items"][0]["archived"]
    assert (root / saved["data"]["path"]).is_file() and snapshot(root) == before
    record("find-archived-cases", "上次单点登录的用例在哪？", "找到了归档的 v1 用例，我会给你来源和留存位置。现在只是查阅，原进度保持不变。",
           {"matched_version": "v1", "archive_preserved": True, "snapshot_exists": True})

    root, ctx, _, _ = fixture("incomplete-material")
    material = out / "incomplete-material/requirement-excerpt.md"
    material.write_text("虚构需求：支持表格批量导入。未说明部分行失败时如何处理。\n")
    assert "未说明" in material.read_text()
    call(root, "state.update", **ctx, expected_revision=1, stages={"analysis": {"status": "in_progress"}}, next="确认部分行失败的处理规则")
    record("incomplete-material", "目前就这段说明，先看看。", "批量导入是已知要求，部分行失败时怎么处理还没交代。我先把这个问题列出来。",
           {"analysis_not_marked_complete": True, "unknown_rule_not_filled_in": True})
    record("requirement-page-conflict", "需求说 100 字，页面只能填 50 字，按哪个来？", "我先核对当前确认的要求和变更记录。若要求仍是 100 字，页面限制就是待核实的问题，不能直接把预期改成 50 字。",
           {"fixture_assumption": "仅评审假设差异，未访问真实页面", "business_bug_submitted": False}, kind="author_instruction_walkthrough_only")

    root, ctx, _, _ = fixture("blocked-environment", with_task=True)
    call(root, "state.update", **ctx, expected_revision=1, stages={"execution": {"status": "blocked", "basis": "虚构环境不可达，仅验证记录"}}, next="环境恢复并明确继续后核对")
    call(root, "case.record", **ctx, task="worker", actor="alice", case="approve", status="blocked", basis="虚构访问阻塞", expected_revision=0)
    summary = call(root, "run.summary", **ctx, run="round-1")
    assert summary["recorded_results"]["blocked"] == 1
    record("unreachable-environment", "QA 打不开了。", "受影响的场景已记为阻塞。之前保存的结果会保留，环境可用后继续时再核对条件。",
           {"fixture_only": True, "blocked_cases": 1, "live_network_checked": False})
    assert summary["pending_sync"] == 2
    record("mind-write-unavailable", "为什么导图还没更新？", "本地结果已保存，导图仍待同步。我会检查实际工具是否可用，写入并回读后才登记完成。",
           {"pending_sync": 2, "mind_calls": 0, "real_connector_status_checked": False})

    root, ctx, _, _ = fixture("timeout", unknown=True)
    before = snapshot(root)
    reject("OPERATION_STATE", root, "operation.dispatch", **ctx, task="worker", actor="alice", operation="write-1", expected_revision=2)
    assert snapshot(root) == before
    record("retry-after-timeout", "刚才超时了，再提一次吧。", "我先查刚才那次有没有成功，免得重复创建。结果查清后再处理。",
           {"duplicate_dispatch_rejected": True, "unknown_result_preserved": True})

    root, ctx, _, proof = fixture("backup-gap")
    (root / proof["snapshot"]).unlink()  # Only this script's synthetic snapshot.
    destination = out / "backup-gap/incomplete.zip"
    reject("BACKUP_INCOMPLETE", root, "backup.create", destination=str(destination))
    assert not destination.exists()
    record("backup-gap", "之前让你备份的资料，都好了吗？", "登记的快照有缺失，备份还不能算完整。我先把缺口列清楚，再按已约定的范围核对来源。",
           {"fixture_prior_authorization": "备份该虚构工作空间", "complete_backup_not_reported": True})

    report = {"version": VERSION, "method": "author-selected actions plus local fixtures; NOT independent model replay",
              "scenario_count": len(reports), "selected_local_actions_checked": sum(r["method"] == "selected_local_actions_checked" for r in reports),
              "instruction_review_only": sum(r["method"] != "selected_local_actions_checked" for r in reports),
              "runtime_calls_including_setup": len(traces), "business_requests": 0,
              "independent_agent_used": False, "model_replay_executed": False, "scenarios": reports}
    (out / "trace.json").write_text(json.dumps(traces, ensure_ascii=False, indent=2) + "\n")
    (out / "walkthrough.json").write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
    print(json.dumps({k: v for k, v in report.items() if k != "scenarios"}, ensure_ascii=False))


if __name__ == "__main__":
    main()
